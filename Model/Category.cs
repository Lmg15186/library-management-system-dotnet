using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Model
{
    // BUSINESS LAYER: Model.
    // Template that represents one row of TabCategory as an object.
    // Same idea as User.cs and Book.cs, but this is the simplest table in the
    // database: it only has an ID and a name.
    //
    //     TabCategory
    //       CID           int          -> primary key
    //       CategoryName  varchar(50)
    //
    // A category is what a book belongs to ("Programming", "Reference"). TabBook
    // stores the CID number in its Category column, and ViewBook joins the two so the
    // search screen can show the readable name instead of the number.
    public class Category
    {
        // Private fields (encapsulation): nothing outside the class writes to these
        // variables directly, everything goes through the properties below.
        private int cId;
        private string categoryName;

        // CID is generated by the database, not by the user. When adding a new
        // category the program does not send a CID at all - SQL Server assigns the
        // next one. That is why the Insert method in CategoryDAO only takes a name.
        public int CID { get => cId; set => cId = value; }

        public string CategoryName { get => categoryName; set => categoryName = value; }

        // Returns the category name when the object is shown as text.
        //
        // A ComboBox calls ToString() on every object it is given, so without this the
        // category drop-down on the book maintenance form would show "Model.Category"
        // on every line. The drop-down displays what this returns, but keeps the whole
        // object behind it, so the form can still read the CID when it needs to save.
        public override string ToString()
        {
            return categoryName;
        }
    }
}