using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Model
{
    // BUSINESS LAYER: Model.
    // Represents one book. It carries two kinds of data, because the book side of the
    // application does two different jobs:
    //
    //  1. SEARCH/BROWSE reads from ViewBook, which joins the tables so a row already
    //     has the readable AuthorName / CategoryName / LanguageName in it.
    //  2. MAINTENANCE writes to TabBook, which only stores the foreign-key NUMBERS
    //     (Author, Category, Language). The maintenance form picks those from
    //     drop-downs, so it needs the IDs, not the names.
    //
    // So this class holds both: the names for display, and the IDs for saving.
    //
    //     TabBook
    //       ISBN         varchar(13)  -> primary key (typed by the user, not generated)
    //       BookName     varchar
    //       Author       int          -> FK to TabAuthor (AID)
    //       Category     int          -> FK to TabCategory (CID)
    //       Language     int          -> FK to TabLanguage (LID)
    //       PublishYear  int
    //       Pages        int
    //       Publisher    varchar
    //
    // Unlike Category, Language and Author, ISBN is NOT generated by the database - the
    // librarian types it in, and it is what identifies the row on update and delete.
    public class Book
    {
        private string isbn;
        private string bookName;
        private string publisher;
        private int publishYear;
        private int pages;

        // Foreign-key IDs (what TabBook actually stores, what the drop-downs save).
        private int authorID;
        private int categoryID;
        private int languageID;

        // Readable names (what ViewBook brings in through its joins, for display).
        private string authorName;
        private string categoryName;
        private string languageName;

        public string ISBN { get => isbn; set => isbn = value; }
        public string BookName { get => bookName; set => bookName = value; }
        public string Publisher { get => publisher; set => publisher = value; }
        public int PublishYear { get => publishYear; set => publishYear = value; }
        public int Pages { get => pages; set => pages = value; }

        public int AuthorID { get => authorID; set => authorID = value; }
        public int CategoryID { get => categoryID; set => categoryID = value; }
        public int LanguageID { get => languageID; set => languageID = value; }

        public string AuthorName { get => authorName; set => authorName = value; }
        public string CategoryName { get => categoryName; set => categoryName = value; }
        public string LanguageName { get => languageName; set => languageName = value; }
    }
}