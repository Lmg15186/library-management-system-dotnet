using System;
using System.Data;
using System.Windows.Forms;

namespace View
{
    // CATEGORY MAINTENANCE SCREEN.
    // Add, update and delete categorys, listed in the grid. It talks only to the
    // MasterService, which groups Category, Language and Author because the brief
    // treats the three as the reference data a staff member maintains.
    public partial class FormCategory : Form
    {
        private MasterServiceRef.MasterService masterService = new MasterServiceRef.MasterService();

        // CID of the row clicked in the grid. 0 means nothing is selected, because the
        // database never generates 0 for an identity column.
        private int selectedCID = 0;

        public FormCategory()
        {
            InitializeComponent();
        }

        private void FormCategory_Load(object sender, EventArgs e)
        {
            LoadCategories();
        }

        // Called on load and after every successful Add, Update or Delete.
        private void LoadCategories()
        {
            try
            {
                dgvCategories.DataSource = null;
                dgvCategories.DataSource = masterService.GetCategories();
            }
            catch (Exception ex)
            {
                MessageBox.Show("Error loading categories: " + CleanMessage(ex));
            }
        }

        // Copies the clicked row into the edit fields.
        private void dgvCategories_CellClick(object sender, DataGridViewCellEventArgs e)
        {
            // RowIndex is -1 when the column header is clicked.
            if (e.RowIndex < 0)
            {
                return;
            }

            // Bound to a DataTable, so the values are read by column name.
            DataGridViewRow row = dgvCategories.Rows[e.RowIndex];

            selectedCID = Convert.ToInt32(row.Cells["CID"].Value);

            txtCID.Text = selectedCID.ToString();
            txtCategoryName.Text = row.Cells["CategoryName"].Value.ToString();
        }

        // ---------- ADD ----------
        private void btnAdd_Click(object sender, EventArgs e)
        {
            try
            {
                // No CID is sent: it is generated by the database.
                int rows = masterService.InsertCategory(txtCategoryName.Text.Trim());

                if (rows > 0)
                {
                    MessageBox.Show("Category added successfully.");
                    ClearFields();
                    LoadCategories();
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show(CleanMessage(ex));
            }
        }

        // ---------- UPDATE ----------
        private void btnUpdate_Click(object sender, EventArgs e)
        {
            try
            {
                if (selectedCID == 0)
                {
                    MessageBox.Show("Please select a category from the list first.");
                    return;
                }

                int rows = masterService.UpdateCategory(selectedCID, txtCategoryName.Text.Trim());

                if (rows > 0)
                {
                    MessageBox.Show("Category updated successfully.");
                    ClearFields();
                    LoadCategories();
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show(CleanMessage(ex));
            }
        }

        // ---------- DELETE ----------
        private void btnDelete_Click(object sender, EventArgs e)
        {
            try
            {
                if (selectedCID == 0)
                {
                    MessageBox.Show("Please select a category from the list first.");
                    return;
                }

                // Deleting cannot be undone, so the operator confirms first.
                DialogResult answer = MessageBox.Show(
                    "Are you sure you want to delete this category?",
                    "Confirm Delete",
                    MessageBoxButtons.YesNo,
                    MessageBoxIcon.Question);

                if (answer == DialogResult.No)
                {
                    return;
                }

                int rows = masterService.DeleteCategory(selectedCID);

                if (rows > 0)
                {
                    MessageBox.Show("Category deleted successfully.");
                    ClearFields();
                    LoadCategories();
                }
            }
            catch (Exception ex)
            {
                // A category still used by a book is protected by the foreign key, so the
                // database refuses the delete.
                MessageBox.Show(
                    "This category cannot be deleted because it is still used by one or more books.\n\n"
                    + "Technical detail: " + CleanMessage(ex));
            }
        }

        // ---------- CLEAR ----------
        private void btnClear_Click(object sender, EventArgs e)
        {
            ClearFields();
        }

        // Empties the fields and forgets the selected row, so the next Add does not
        // reuse the last category that was clicked.
        private void ClearFields()
        {
            selectedCID = 0;
            txtCID.Clear();
            txtCategoryName.Clear();
            txtCategoryName.Focus();
        }

        // A rule broken inside the service comes back wrapped by SOAP, with the
        // exception type and the stack trace attached. This keeps only the sentence.
        private string CleanMessage(Exception ex)
        {
            string message = ex.Message;

            int arrow = message.LastIndexOf("---> ");
            if (arrow >= 0)
            {
                message = message.Substring(arrow + 5);
            }

            // The rest is the stack trace.
            int lineBreak = message.IndexOf('\n');
            if (lineBreak >= 0)
            {
                message = message.Substring(0, lineBreak);
            }

            // Drop the type name .NET puts in front.
            if (message.StartsWith("System."))
            {
                int colon = message.IndexOf(": ");
                if (colon >= 0)
                {
                    message = message.Substring(colon + 2);
                }
            }

            return message.Trim();
        }
    }
}