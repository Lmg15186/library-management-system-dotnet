using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using Model.DataSetLibrarySystemTableAdapters; // I need this to "see" the TabCategoryTableAdapter

namespace Model
{
    // DATA ACCESS LAYER for categories.
    // This is the only class that talks to the TabCategoryTableAdapter. It runs the
    // commands and returns the raw table exactly as it came from the database.
    // Turning rows into Category objects is the job of CategoryLogic.
    //
    // This DAO is different from BookDAO in one important way: it both reads AND
    // writes. BookDAO only reads, because the search screen reads from ViewBook, and a
    // view with joins cannot be written to. TabCategory is a real table, so the
    // maintenance screen can insert, update and delete rows in it.
    public class CategoryDAO
    {
        // The TableAdapter is the bridge Visual Studio generated from the DataSet.
        // It is what actually executes the SQL against the database.
        private TabCategoryTableAdapter tabCategoryTableAdapter = new TabCategoryTableAdapter();

        // -------- READ --------

        // Returns every category in the database.
        // Used by the maintenance grid, and later by the category drop-down on the
        // book maintenance form.
        public DataSetLibrarySystem.TabCategoryDataTable BrowseCategories()
        {
            return tabCategoryTableAdapter.GetData();
        }

        // -------- WRITE --------
        // The three methods below were generated by the DataSet wizard when I ticked
        // "Create methods to send updates directly to the database"
        // (GenerateDBDirectMethods). Visual Studio read the primary key of TabCategory
        // and wrote the SQL for me, so I only have to call the methods.
        //
        // They all return an int: the number of rows the command affected. That number
        // is how the program knows whether the operation actually did anything, which
        // is why every method here passes it back up to the logic layer instead of
        // ignoring it.

        // Inserts a new category and returns the number of rows inserted.
        //
        // Notice there is no CID parameter. CID is an identity column, so SQL Server
        // assigns the next number itself. The generated command is:
        //     INSERT INTO [TabCategory] ([CategoryName]) VALUES (@CategoryName)
        public int Insert(string categoryName)
        {
            return tabCategoryTableAdapter.Insert(categoryName);
        }

        // Updates an existing category and returns the number of rows updated.
        //
        // The generated command is:
        //     UPDATE [TabCategory] SET [CategoryName] = @CategoryName
        //     WHERE ([CID] = @Original_CID)
        //
        // So it needs two values: the new name, and the CID of the row to change. The
        // parameter is called Original_CID because the wizard names it after the value
        // the row had when it was loaded - it is what identifies which record to write
        // over, not a value being written.
        public int Update(string categoryName, int cid)
        {
            return tabCategoryTableAdapter.Update(categoryName, cid);
        }

        // Deletes a category and returns the number of rows deleted.
        //
        // The generated command is:
        //     DELETE FROM [TabCategory] WHERE ([CID] = @Original_CID)
        public int Delete(int cid)
        {
            return tabCategoryTableAdapter.Delete(cid);
        }
    }
}