using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using Model.DataSetLibrarySystemTableAdapters; // I need this to "see" the TabLanguageTableAdapter

namespace Model
{
    // DATA ACCESS LAYER for languages.
    // This is the only class that talks to the TabLanguageTableAdapter. It runs the
    // commands and returns the raw table exactly as it came from the database.
    // Turning rows into Language objects is the job of LanguageLogic.
    //
    // Like TabCategory, TabLanguage is a real table (not a view), so this DAO both
    // reads AND writes: the maintenance screen can insert, update and delete rows.
    public class LanguageDAO
    {
        // The TableAdapter is the bridge Visual Studio generated from the DataSet.
        // It is what actually executes the SQL against the database.
        private TabLanguageTableAdapter tabLanguageTableAdapter = new TabLanguageTableAdapter();

        // -------- READ --------
        // Returns every language in the database.
        // Used by the maintenance grid, and later by the language drop-down on the
        // book maintenance form.
        public DataSetLibrarySystem.TabLanguageDataTable BrowseLanguages()
        {
            return tabLanguageTableAdapter.GetData();
        }

        // -------- WRITE --------
        // The three methods below were generated by the DataSet wizard when I ticked
        // "Create methods to send updates directly to the database"
        // (GenerateDBDirectMethods). They all return an int: the number of rows the
        // command affected, so the logic layer can tell whether it did anything.

        // Inserts a new language and returns the number of rows inserted.
        // LID is an identity column, so SQL Server assigns the next number itself:
        //     INSERT INTO [TabLanguage] ([LanguageName]) VALUES (@LanguageName)
        public int Insert(string languageName)
        {
            return tabLanguageTableAdapter.Insert(languageName);
        }

        // Updates an existing language and returns the number of rows updated.
        //     UPDATE [TabLanguage] SET [LanguageName] = @LanguageName
        //     WHERE ([LID] = @Original_LID)
        public int Update(string languageName, int lid)
        {
            return tabLanguageTableAdapter.Update(languageName, lid);
        }

        // Deletes a language and returns the number of rows deleted.
        //     DELETE FROM [TabLanguage] WHERE ([LID] = @Original_LID)
        public int Delete(int lid)
        {
            return tabLanguageTableAdapter.Delete(lid);
        }
    }
}