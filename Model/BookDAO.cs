using System;
using System.Collections.Generic;
using System.Data;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using Model.DataSetLibrarySystemTableAdapters;

namespace Model
{
    // DATA ACCESS LAYER for Book.
    //
    // The book side reads and writes through two different adapters, on purpose:
    //  - READS (browse/search) go through ViewBookTableAdapter. ViewBook is a join, so
    //    a row comes back with "Bruce Eckel" already in it instead of the number 3.
    //  - WRITES (add/update/delete) go through TabBookTableAdapter. A view with joins
    //    cannot be written to, so maintenance has to target the real TabBook table.
    public class BookDAO
    {
        private ViewBookTableAdapter viewBookTableAdapter = new ViewBookTableAdapter();
        private TabBookTableAdapter tabBookTableAdapter = new TabBookTableAdapter();

        // ================= READ (from ViewBook) =================

        // Browse: all books.
        public DataSetLibrarySystem.ViewBookDataTable BrowseBooks()
        {
            return viewBookTableAdapter.GetData();
        }

        // Search 1: by book name. The % wildcards are added here so the librarian can
        // type part of a title and still match it, instead of needing the exact name.
        public DataSetLibrarySystem.ViewBookDataTable SearchByBookName(string bookName)
        {
            return viewBookTableAdapter.GetDataByBookName("%" + bookName + "%");
        }

        // Search 2: by author (partial match).
        public DataSetLibrarySystem.ViewBookDataTable SearchByAuthor(string authorName)
        {
            return viewBookTableAdapter.GetDataByAuthor("%" + authorName + "%");
        }

        // Search 3: by category (partial match).
        public DataSetLibrarySystem.ViewBookDataTable SearchByCategory(string categoryName)
        {
            return viewBookTableAdapter.GetDataByCategory("%" + categoryName + "%");
        }

        // ================= WRITE (to TabBook) =================
        // These match the Insert/Update/Delete the DataSet generated for TabBook.
        // Each returns the number of rows affected, so the logic layer can tell whether
        // the command did anything.

        // Insert takes every column, including the ISBN, because ISBN is typed by the
        // librarian and is not generated by the database.
        //     INSERT INTO [TabBook] (ISBN, BookName, Author, Category, Language,
        //         PublishYear, Pages, Publisher) VALUES (...)
        public int Insert(string isbn, string bookName, int author, int category,
                          int language, int publishYear, int pages, string publisher)
        {
            return tabBookTableAdapter.Insert(isbn, bookName, author, category,
                                              language, publishYear, pages, publisher);
        }

        // Update writes all columns and finds the row by its original ISBN. The DataSet
        // generated the command with ISBN in the SET as well, so the last argument is
        // the original ISBN used in the WHERE clause.
        //     UPDATE [TabBook] SET ISBN=@ISBN, BookName=@BookName, ...
        //     WHERE (ISBN = @Original_ISBN)
        public int Update(string isbn, string bookName, int author, int category,
                          int language, int publishYear, int pages, string publisher,
                          string originalIsbn)
        {
            return tabBookTableAdapter.Update(isbn, bookName, author, category,
                                              language, publishYear, pages, publisher,
                                              originalIsbn);
        }

        // Delete finds the row by its ISBN.
        //     DELETE FROM [TabBook] WHERE (ISBN = @Original_ISBN)
        public int Delete(string isbn)
        {
            return tabBookTableAdapter.Delete(isbn);
        }
    }
}