using System;
using System.Data;
using System.Windows.Forms;

namespace View
{
    // LANGUAGE MAINTENANCE SCREEN.
    // Add, update and delete languages, listed in the grid. It talks only to the
    // MasterService, which groups Category, Language and Author because the brief
    // treats the three as the reference data a staff member maintains.
    public partial class FormLanguage : Form
    {
        private MasterServiceRef.MasterService masterService = new MasterServiceRef.MasterService();

        // LID of the row clicked in the grid. 0 means nothing is selected, because the
        // database never generates 0 for an identity column.
        private int selectedLID = 0;

        public FormLanguage()
        {
            InitializeComponent();
        }

        private void FormLanguage_Load(object sender, EventArgs e)
        {
            LoadLanguages();
        }

        // Called on load and after every successful Add, Update or Delete.
        private void LoadLanguages()
        {
            try
            {
                dgvLanguages.DataSource = null;
                dgvLanguages.DataSource = masterService.GetLanguages();
            }
            catch (Exception ex)
            {
                MessageBox.Show("Error loading languages: " + CleanMessage(ex));
            }
        }

        // Copies the clicked row into the edit fields.
        private void dgvLanguages_CellClick(object sender, DataGridViewCellEventArgs e)
        {
            // RowIndex is -1 when the column header is clicked.
            if (e.RowIndex < 0)
            {
                return;
            }

            // Bound to a DataTable, so the values are read by column name.
            DataGridViewRow row = dgvLanguages.Rows[e.RowIndex];

            selectedLID = Convert.ToInt32(row.Cells["LID"].Value);

            txtLID.Text = selectedLID.ToString();
            txtLanguageName.Text = row.Cells["LanguageName"].Value.ToString();
        }

        // ---------- ADD ----------
        private void btnAdd_Click(object sender, EventArgs e)
        {
            try
            {
                // No LID is sent: it is generated by the database.
                int rows = masterService.InsertLanguage(txtLanguageName.Text.Trim());

                if (rows > 0)
                {
                    MessageBox.Show("Language added successfully.");
                    ClearFields();
                    LoadLanguages();
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show(CleanMessage(ex));
            }
        }

        // ---------- UPDATE ----------
        private void btnUpdate_Click(object sender, EventArgs e)
        {
            try
            {
                if (selectedLID == 0)
                {
                    MessageBox.Show("Please select a language from the list first.");
                    return;
                }

                int rows = masterService.UpdateLanguage(selectedLID, txtLanguageName.Text.Trim());

                if (rows > 0)
                {
                    MessageBox.Show("Language updated successfully.");
                    ClearFields();
                    LoadLanguages();
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show(CleanMessage(ex));
            }
        }

        // ---------- DELETE ----------
        private void btnDelete_Click(object sender, EventArgs e)
        {
            try
            {
                if (selectedLID == 0)
                {
                    MessageBox.Show("Please select a language from the list first.");
                    return;
                }

                // Deleting cannot be undone, so the operator confirms first.
                DialogResult answer = MessageBox.Show(
                    "Are you sure you want to delete this language?",
                    "Confirm Delete",
                    MessageBoxButtons.YesNo,
                    MessageBoxIcon.Question);

                if (answer == DialogResult.No)
                {
                    return;
                }

                int rows = masterService.DeleteLanguage(selectedLID);

                if (rows > 0)
                {
                    MessageBox.Show("Language deleted successfully.");
                    ClearFields();
                    LoadLanguages();
                }
            }
            catch (Exception ex)
            {
                // A language still used by a book is protected by the foreign key, so the
                // database refuses the delete.
                MessageBox.Show(
                    "This language cannot be deleted because it is still used by one or more books.\n\n"
                    + "Technical detail: " + CleanMessage(ex));
            }
        }

        // ---------- CLEAR ----------
        private void btnClear_Click(object sender, EventArgs e)
        {
            ClearFields();
        }

        // Empties the fields and forgets the selected row, so the next Add does not
        // reuse the last language that was clicked.
        private void ClearFields()
        {
            selectedLID = 0;
            txtLID.Clear();
            txtLanguageName.Clear();
            txtLanguageName.Focus();
        }

        // A rule broken inside the service comes back wrapped by SOAP, with the
        // exception type and the stack trace attached. This keeps only the sentence.
        private string CleanMessage(Exception ex)
        {
            string message = ex.Message;

            int arrow = message.LastIndexOf("---> ");
            if (arrow >= 0)
            {
                message = message.Substring(arrow + 5);
            }

            // The rest is the stack trace.
            int lineBreak = message.IndexOf('\n');
            if (lineBreak >= 0)
            {
                message = message.Substring(0, lineBreak);
            }

            // Drop the type name .NET puts in front.
            if (message.StartsWith("System."))
            {
                int colon = message.IndexOf(": ");
                if (colon >= 0)
                {
                    message = message.Substring(colon + 2);
                }
            }

            return message.Trim();
        }
    }
}