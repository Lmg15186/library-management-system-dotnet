using System;
using System.Data;
using System.Windows.Forms;

namespace View
{
    // AUTHOR MAINTENANCE SCREEN.
    // Add, update and delete authors, listed in the grid. It talks only to the
    // MasterService, which groups Category, Language and Author because the brief
    // treats the three as the reference data a staff member maintains.
    public partial class FormAuthor : Form
    {
        private MasterServiceRef.MasterService masterService = new MasterServiceRef.MasterService();

        // AID of the row clicked in the grid. 0 means nothing is selected, because the
        // database never generates 0 for an identity column.
        private int selectedAID = 0;

        public FormAuthor()
        {
            InitializeComponent();
        }

        private void FormAuthor_Load(object sender, EventArgs e)
        {
            LoadAuthors();
        }

        // Called on load and after every successful Add, Update or Delete.
        private void LoadAuthors()
        {
            try
            {
                dgvAuthors.DataSource = null;
                dgvAuthors.DataSource = masterService.GetAuthors();
            }
            catch (Exception ex)
            {
                MessageBox.Show("Error loading authors: " + CleanMessage(ex));
            }
        }

        // Copies the clicked row into the edit fields.
        private void dgvAuthors_CellClick(object sender, DataGridViewCellEventArgs e)
        {
            // RowIndex is -1 when the column header is clicked.
            if (e.RowIndex < 0)
            {
                return;
            }

            // Bound to a DataTable, so the values are read by column name.
            DataGridViewRow row = dgvAuthors.Rows[e.RowIndex];

            selectedAID = Convert.ToInt32(row.Cells["AID"].Value);

            txtAID.Text = selectedAID.ToString();
            txtAuthorName.Text = row.Cells["AuthorName"].Value.ToString();
        }

        // ---------- ADD ----------
        private void btnAdd_Click(object sender, EventArgs e)
        {
            try
            {
                // No AID is sent: it is generated by the database.
                int rows = masterService.InsertAuthor(txtAuthorName.Text.Trim());

                if (rows > 0)
                {
                    MessageBox.Show("Author added successfully.");
                    ClearFields();
                    LoadAuthors();
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show(CleanMessage(ex));
            }
        }

        // ---------- UPDATE ----------
        private void btnUpdate_Click(object sender, EventArgs e)
        {
            try
            {
                if (selectedAID == 0)
                {
                    MessageBox.Show("Please select a author from the list first.");
                    return;
                }

                int rows = masterService.UpdateAuthor(selectedAID, txtAuthorName.Text.Trim());

                if (rows > 0)
                {
                    MessageBox.Show("Author updated successfully.");
                    ClearFields();
                    LoadAuthors();
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show(CleanMessage(ex));
            }
        }

        // ---------- DELETE ----------
        private void btnDelete_Click(object sender, EventArgs e)
        {
            try
            {
                if (selectedAID == 0)
                {
                    MessageBox.Show("Please select a author from the list first.");
                    return;
                }

                // Deleting cannot be undone, so the operator confirms first.
                DialogResult answer = MessageBox.Show(
                    "Are you sure you want to delete this author?",
                    "Confirm Delete",
                    MessageBoxButtons.YesNo,
                    MessageBoxIcon.Question);

                if (answer == DialogResult.No)
                {
                    return;
                }

                int rows = masterService.DeleteAuthor(selectedAID);

                if (rows > 0)
                {
                    MessageBox.Show("Author deleted successfully.");
                    ClearFields();
                    LoadAuthors();
                }
            }
            catch (Exception ex)
            {
                // A author still used by a book is protected by the foreign key, so the
                // database refuses the delete.
                MessageBox.Show(
                    "This author cannot be deleted because it is still used by one or more books.\n\n"
                    + "Technical detail: " + CleanMessage(ex));
            }
        }

        // ---------- CLEAR ----------
        private void btnClear_Click(object sender, EventArgs e)
        {
            ClearFields();
        }

        // Empties the fields and forgets the selected row, so the next Add does not
        // reuse the last author that was clicked.
        private void ClearFields()
        {
            selectedAID = 0;
            txtAID.Clear();
            txtAuthorName.Clear();
            txtAuthorName.Focus();
        }

        // A rule broken inside the service comes back wrapped by SOAP, with the
        // exception type and the stack trace attached. This keeps only the sentence.
        private string CleanMessage(Exception ex)
        {
            string message = ex.Message;

            int arrow = message.LastIndexOf("---> ");
            if (arrow >= 0)
            {
                message = message.Substring(arrow + 5);
            }

            // The rest is the stack trace.
            int lineBreak = message.IndexOf('\n');
            if (lineBreak >= 0)
            {
                message = message.Substring(0, lineBreak);
            }

            // Drop the type name .NET puts in front.
            if (message.StartsWith("System."))
            {
                int colon = message.IndexOf(": ");
                if (colon >= 0)
                {
                    message = message.Substring(colon + 2);
                }
            }

            return message.Trim();
        }
    }
}