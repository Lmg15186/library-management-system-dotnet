using System;
using System.Data;
using System.Windows.Forms;

namespace View
{
    // BOOK MAINTENANCE SCREEN. Add, update and delete books, listed in the grid.
    // Uses two services: BookService for the books, MasterService for the three
    // drop-downs (author, category and language are foreign keys, so they are chosen
    // and not typed).
    public partial class FormBookMaintenance : Form
    {
        private BookServiceRef.BookService bookService = new BookServiceRef.BookService();
        private MasterServiceRef.MasterService masterService = new MasterServiceRef.MasterService();

        // ISBN of the row clicked. The ISBN itself can be edited, so the original is
        // what locates the row on Update.
        private string selectedIsbn = "";

        public FormBookMaintenance()
        {
            InitializeComponent();
        }

        // Fills the three drop-downs first, then the grid.
        private void FormBookMaintenance_Load(object sender, EventArgs e)
        {
            LoadDropDowns();
            LoadBooks();
        }

        // ---------- Fill the drop-downs ----------
        // ValueMember is the ID column and DisplayMember the name, so the box shows the
        // name and SelectedValue gives back the number TabBook stores.
        private void LoadDropDowns()
        {
            try
            {
                cmbAuthor.DataSource = masterService.GetAuthors();
                cmbAuthor.ValueMember = "AID";
                cmbAuthor.DisplayMember = "AuthorName";

                cmbCategory.DataSource = masterService.GetCategories();
                cmbCategory.ValueMember = "CID";
                cmbCategory.DisplayMember = "CategoryName";

                cmbLanguage.DataSource = masterService.GetLanguages();
                cmbLanguage.ValueMember = "LID";
                cmbLanguage.DisplayMember = "LanguageName";
            }
            catch (Exception ex)
            {
                MessageBox.Show("Error loading drop-down lists: " + CleanMessage(ex));
            }
        }

        // ---------- Fill the grid ----------
        private void LoadBooks()
        {
            try
            {
                dgvBooks.DataSource = null;
                dgvBooks.DataSource = bookService.GetBooks();
            }
            catch (Exception ex)
            {
                MessageBox.Show("Error loading books: " + CleanMessage(ex));
            }
        }

        // ---------- Grid row clicked: load it into the fields ----------
        private void dgvBooks_CellClick(object sender, DataGridViewCellEventArgs e)
        {
            if (e.RowIndex < 0)
            {
                return;
            }

            // Bound to a DataTable now, so the values are read by column name.
            DataGridViewRow row = dgvBooks.Rows[e.RowIndex];

            selectedIsbn = row.Cells["ISBN"].Value.ToString();

            txtISBN.Text = selectedIsbn;
            txtBookName.Text = row.Cells["BookName"].Value.ToString();
            txtPublishYear.Text = row.Cells["PublishYear"].Value.ToString();
            txtPages.Text = row.Cells["Pages"].Value.ToString();
            txtPublisher.Text = row.Cells["Publisher"].Value.ToString();

            // Move each drop-down to the ID this book uses.
            cmbAuthor.SelectedValue = Convert.ToInt32(row.Cells["AuthorID"].Value);
            cmbCategory.SelectedValue = Convert.ToInt32(row.Cells["CategoryID"].Value);
            cmbLanguage.SelectedValue = Convert.ToInt32(row.Cells["LanguageID"].Value);
        }

        // A non-numeric entry becomes 0, which the service rejects with a message
        // instead of the program crashing.
        private int ReadNumber(TextBox box)
        {
            int value;
            int.TryParse(box.Text, out value);
            return value;
        }

        // SelectedValue is null when the list is empty.
        private int ReadComboId(ComboBox combo)
        {
            return (combo.SelectedValue != null) ? Convert.ToInt32(combo.SelectedValue) : 0;
        }

        // ---------- ADD ----------
        private void btnAdd_Click(object sender, EventArgs e)
        {
            try
            {
                // The ISBN is sent in because it is typed by the librarian, not
                // generated by the database.
                int rows = bookService.InsertBook(txtISBN.Text.Trim(),
                                                  txtBookName.Text.Trim(),
                                                  ReadComboId(cmbAuthor),
                                                  ReadComboId(cmbCategory),
                                                  ReadComboId(cmbLanguage),
                                                  ReadNumber(txtPublishYear),
                                                  ReadNumber(txtPages),
                                                  txtPublisher.Text.Trim());

                if (rows > 0)
                {
                    MessageBox.Show("Book added successfully.");
                    ClearFields();
                    LoadBooks();
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show(CleanMessage(ex));
            }
        }

        // ---------- UPDATE ----------
        private void btnUpdate_Click(object sender, EventArgs e)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(selectedIsbn))
                {
                    MessageBox.Show("Please select a book from the list first.");
                    return;
                }

                int rows = bookService.UpdateBook(txtISBN.Text.Trim(),
                                                  txtBookName.Text.Trim(),
                                                  ReadComboId(cmbAuthor),
                                                  ReadComboId(cmbCategory),
                                                  ReadComboId(cmbLanguage),
                                                  ReadNumber(txtPublishYear),
                                                  ReadNumber(txtPages),
                                                  txtPublisher.Text.Trim(),
                                                  selectedIsbn);

                if (rows > 0)
                {
                    MessageBox.Show("Book updated successfully.");
                    ClearFields();
                    LoadBooks();
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show(CleanMessage(ex));
            }
        }

        // ---------- DELETE ----------
        private void btnDelete_Click(object sender, EventArgs e)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(selectedIsbn))
                {
                    MessageBox.Show("Please select a book from the list first.");
                    return;
                }

                // Deleting cannot be undone, so the operator confirms first.
                DialogResult answer = MessageBox.Show(
                    "Are you sure you want to delete this book?",
                    "Confirm Delete",
                    MessageBoxButtons.YesNo,
                    MessageBoxIcon.Question);

                if (answer == DialogResult.No)
                {
                    return;
                }

                int rows = bookService.DeleteBook(selectedIsbn);

                if (rows > 0)
                {
                    MessageBox.Show("Book deleted successfully.");
                    ClearFields();
                    LoadBooks();
                }
            }
            catch (Exception ex)
            {
                // A borrow or reserve row pointing at this book blocks the delete.
                MessageBox.Show(
                    "This book cannot be deleted because it is still used by a borrow or reserve record.\n\n"
                    + "Technical detail: " + CleanMessage(ex));
            }
        }

        // ---------- CLEAR ----------
        private void btnClear_Click(object sender, EventArgs e)
        {
            ClearFields();
        }

        // Empties the fields and forgets the selected row.
        private void ClearFields()
        {
            selectedIsbn = "";
            txtISBN.Clear();
            txtBookName.Clear();
            txtPublishYear.Clear();
            txtPages.Clear();
            txtPublisher.Clear();
            txtISBN.Focus();
        }

        // A rule broken inside the service comes back wrapped by SOAP, with the
        // exception type and the stack trace attached. This keeps only the sentence.
        private string CleanMessage(Exception ex)
        {
            string message = ex.Message;

            int arrow = message.LastIndexOf("---> ");
            if (arrow >= 0)
            {
                message = message.Substring(arrow + 5);
            }

            // The rest is the stack trace.
            int lineBreak = message.IndexOf('\n');
            if (lineBreak >= 0)
            {
                message = message.Substring(0, lineBreak);
            }

            // Drop the type name .NET puts in front.
            if (message.StartsWith("System."))
            {
                int colon = message.IndexOf(": ");
                if (colon >= 0)
                {
                    message = message.Substring(colon + 2);
                }
            }

            return message.Trim();
        }
    }
}