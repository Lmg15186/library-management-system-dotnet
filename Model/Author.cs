using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Model
{
    // BUSINESS LAYER: Model.
    // Represents one row of TabAuthor as an object. Same idea as Category and
    // Language - just an ID and a name.
    //
    //     TabAuthor
    //       AID          int          -> primary key
    //       AuthorName   varchar(50)
    //
    // TabBook stores the AID in its Author column, and ViewBook joins the two so the
    // search screen can show the author's name instead of the number.
    public class Author
    {
        private int aId;
        private string authorName;

        // AID is generated by the database, so a new author is inserted with a name
        // only - SQL Server assigns the next AID.
        public int AID { get => aId; set => aId = value; }
        public string AuthorName { get => authorName; set => authorName = value; }

        // A ComboBox calls ToString() on each item, so returning the name here means
        // the author drop-down on the book form shows the name, not "Model.Author",
        // while still keeping the whole object (and its AID) behind it.
        public override string ToString()
        {
            return authorName;
        }
    }
}