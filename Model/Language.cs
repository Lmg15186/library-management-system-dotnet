using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Model
{
    // BUSINESS LAYER: Model.
    // Template that represents one row of TabLanguage as an object.
    // Same idea as Category.cs - the simplest kind of table, just an ID and a name.
    //
    //     TabLanguage
    //       LID           int          -> primary key
    //       LanguageName  varchar(50)
    //
    // A language is what a book is written in ("English", "Portuguese"). TabBook
    // stores the LID number in its Language column, and ViewBook joins the two so the
    // search screen can show the readable name instead of the number.
    public class Language
    {
        // Private fields (encapsulation): everything goes through the properties below.
        private int lId;
        private string languageName;

        // LID is generated by the database, not by the user. When adding a new
        // language the program does not send an LID at all - SQL Server assigns the
        // next one. That is why the Insert method in LanguageDAO only takes a name.
        public int LID { get => lId; set => lId = value; }
        public string LanguageName { get => languageName; set => languageName = value; }

        // Returns the language name when the object is shown as text.
        //
        // A ComboBox calls ToString() on every object it is given, so without this the
        // language drop-down on the book maintenance form would show "Model.Language"
        // on every line. The drop-down displays what this returns, but keeps the whole
        // object behind it, so the form can still read the LID when it needs to save.
        public override string ToString()
        {
            return languageName;
        }
    }
}